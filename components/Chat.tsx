"use client";

import { useCallback, useEffect, useRef, useState } from "react";
import { useChat, type ChatStore } from "@/lib/useChat";
import ChatInput from "./ChatInput";
import EmptyState from "./EmptyState";
import ErrorBanner from "./ErrorBanner";
import LoadingBubble from "./LoadingBubble";
import MessageBubble from "./MessageBubble";
import { ChevronDownIcon } from "./Icons";

/** How close to the bottom still counts as "following along". */
const STICK_THRESHOLD_PX = 120;

export default function Chat({ store }: { store?: ChatStore }) {
  const {
    messages,
    input,
    setInput,
    isLoading,
    isWaitingForFirstToken,
    error,
    sendMessage,
    stop,
    retryLast,
    dismissError,
    hydrated,
  } = useChat(store);

  const scrollRef = useRef<HTMLDivElement>(null);
  const bottomRef = useRef<HTMLDivElement>(null);
  const [atBottom, setAtBottom] = useState(true);

  const scrollToBottom = useCallback((behavior: ScrollBehavior = "smooth") => {
    bottomRef.current?.scrollIntoView({ behavior, block: "end" });
  }, []);

  const handleScroll = useCallback(() => {
    const el = scrollRef.current;
    if (!el) return;
    const distance = el.scrollHeight - el.scrollTop - el.clientHeight;
    setAtBottom(distance < STICK_THRESHOLD_PX);
  }, []);

  // Follow the answer as it streams, but never yank a user who scrolled up.
  useEffect(() => {
    if (atBottom) scrollToBottom(isLoading ? "auto" : "smooth");
  }, [messages, isWaitingForFirstToken, atBottom, isLoading, scrollToBottom]);

  const lastMessage = messages.at(-1);
  const streamingId =
    isLoading && !isWaitingForFirstToken && lastMessage?.role === "assistant"
      ? lastMessage.id
      : null;
  const canRegenerate = !isLoading && lastMessage?.role === "assistant" && !lastMessage.error;

  const isBlank = hydrated && messages.length === 0 && !isLoading;

  const composer = (
    <ChatInput
      value={input}
      onChange={setInput}
      onSubmit={() => void sendMessage()}
      onStop={stop}
      isLoading={isLoading}
      disabled={!hydrated}
      autoFocus={isBlank}
    />
  );

  if (isBlank) {
    return (
      <div className="flex flex-1 flex-col items-center justify-center overflow-y-auto px-4 pb-16">
        <div className="w-full max-w-3xl">
          <h1 className="mb-7 text-center text-[1.75rem] font-semibold tracking-tight">
            What can I help with?
          </h1>

          {error && (
            <ErrorBanner message={error} onDismiss={dismissError} />
          )}

          {composer}

          <div className="mt-4">
            <EmptyState onPick={(prompt) => void sendMessage(prompt)} />
          </div>
        </div>
      </div>
    );
  }

  return (
    <>
      <div
        ref={scrollRef}
        onScroll={handleScroll}
        role="log"
        aria-live="polite"
        aria-label="Conversation"
        className="scroll-host min-h-0 flex-1 overflow-y-auto"
      >
        <div className="mx-auto flex w-full max-w-3xl flex-col gap-7 px-4 pt-4 pb-10">
          {messages.map((message) => (
            <MessageBubble
              key={message.id}
              message={message}
              streaming={message.id === streamingId}
              onRegenerate={
                canRegenerate && message.id === lastMessage?.id
                  ? () => void retryLast()
                  : undefined
              }
            />
          ))}

          {isWaitingForFirstToken && <LoadingBubble />}
          <div ref={bottomRef} />
        </div>
      </div>

      <div className="relative shrink-0 px-4 pb-3">
        {!atBottom && (
          <button
            type="button"
            onClick={() => scrollToBottom()}
            aria-label="Scroll to latest message"
            className="animate-pop absolute -top-11 left-1/2 z-10 flex size-9 -translate-x-1/2 items-center justify-center rounded-full border border-line bg-canvas text-muted shadow-pop transition-colors hover:text-primary"
          >
            <ChevronDownIcon size={18} />
          </button>
        )}

        {error && (
          <ErrorBanner
            message={error}
            onRetry={isLoading ? undefined : () => void retryLast()}
            onDismiss={dismissError}
          />
        )}

        <div className="mx-auto w-full max-w-3xl">
          {composer}
          <p className="pt-2 text-center text-xs text-faint">
            Responses are generated by AI and may be inaccurate.
          </p>
        </div>
      </div>
    </>
  );
}
